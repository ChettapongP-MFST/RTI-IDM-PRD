#!/usr/bin/env python3
"""Melt the 3 wide customer trigger-threshold matrices into one tidy EWI CSV.

Source (local, gitignored): input/Trigger Requirement_<date>_<scope>.csv
  - each file = 8 indicator blocks x (L1/L2/L3) x (4 windows) x (3 day types)
Output (committed): production/04-gold-summary-table/data/ewi-alert-threshold.csv
  - one row per Scope x IndicatorKey x WindowCode x DayType with L1/L2/L3.

Re-run whenever the customer resends thresholds. `xx` / blank cells -> empty (null).
"""
from __future__ import annotations

import csv
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
INPUT_DIR = REPO / "input"
OUT = REPO / "production" / "04-gold-summary-table" / "data" / "ewi-alert-threshold.csv"
OUT_KQL = REPO / "production" / "04-gold-summary-table" / "kql" / "17-load-EWI_AlertThreshold.kql"

DATE_TAG = "15Sep2026"
SCOPE_FILES = {
    "TOTAL_BANK": f"Trigger Requirement_{DATE_TAG}_Total Bank.csv",
    "RETAILS": f"Trigger Requirement_{DATE_TAG}_Retails.csv",
    "NON_RETAILS": f"Trigger Requirement_{DATE_TAG}_Non-Retails.csv",
}

# IndicatorId -> (IndicatorKey matching Gold_EarlyWarning output column, Direction)
INDICATORS = {
    1: ("GrossOutflow_MB", "HIGH_IS_BAD"),
    2: ("NetOutflow_MB", "LOW_IS_BAD"),
    3: ("AccumNetOutflow_MB", "LOW_IS_BAD"),
    4: ("DebitTxnCount_M", "HIGH_IS_BAD"),
    5: ("Velocity_X", "HIGH_IS_BAD"),
    6: ("AvgDebitAmount_MB", "HIGH_IS_BAD"),
    7: ("ClusterShare_Pct", "HIGH_IS_BAD"),
    8: ("ShareJump_Pct", "HIGH_IS_BAD"),
}

WINDOWS = [
    "BEFORE_WORKING_HOUR",
    "MORNING_WORKING_HOUR",
    "AFTERNOON_WORKING_HOUR",
    "AFTER_WORKING_HOUR",
]
WIN_BASECOL = [2, 6, 10, 14]          # first data column of each window block
DAYTYPES = ["BUSINESS_DAY", "WEEKEND", "HOLIDAY"]  # offsets 0,1,2 within a window

BLOCK_RE = re.compile(r"^\s*(\d+)\.\s")


def clean(v: str) -> str:
    v = (v or "").strip()
    return "" if v.lower() in ("", "xx") else v


def parse_scope(path: Path) -> dict:
    """Return {(indicatorId, window, daytype): {L1,L2,L3}}."""
    rows = list(csv.reader(path.open(newline="", encoding="utf-8-sig")))
    out: dict = {}
    current = None  # active indicatorId
    for r in rows:
        col0 = r[0].strip() if r else ""
        m = BLOCK_RE.match(col0)
        if m:
            current = int(m.group(1))
            continue
        if current is None or len(r) < 2:
            continue
        label = r[1].strip()
        lvl = None
        if label.startswith("L1"):
            lvl = "L1"
        elif label.startswith("L2"):
            lvl = "L2"
        elif label.startswith("L3"):
            lvl = "L3"
        if lvl is None:
            continue
        for w, base in zip(WINDOWS, WIN_BASECOL):
            for d, off in zip(DAYTYPES, range(3)):
                col = base + off
                val = clean(r[col]) if col < len(r) else ""
                out.setdefault((current, w, d), {})[lvl] = val
    return out


def _num_or_null(v: str) -> str:
    """KQL real literal for the datatable: value or real(null)."""
    return v if v else "real(null)"


def write_kql(rows: list[list[str]]) -> None:
    """Emit an idempotent .set-or-replace loader (datatable) for EWI_AlertThreshold."""
    lines = [
        "// ============================================================================",
        "// Production 04 - Load EWI_AlertThreshold from the tidy threshold template.",
        "// ----------------------------------------------------------------------------",
        "// GENERATED by resources/datasets/melt_trigger_thresholds.py - DO NOT EDIT BY HAND.",
        "// Source: production/04-gold-summary-table/data/ewi-alert-threshold.csv",
        "// Re-run the melt script after the customer resends thresholds, then re-run this.",
        "//",
        "// .set-or-replace fully replaces the table contents (idempotent).",
        "// Run in the DepositMovement KQL database (inside Eventhouse eh-rti-deposit).",
        "// ============================================================================",
        "",
        ".set-or-replace EWI_AlertThreshold <|",
        "    datatable(Scope: string, IndicatorId: int, IndicatorKey: string,"
        " WindowCode: string, DayType: string, Direction: string,"
        " L1: real, L2: real, L3: real)",
        "    [",
    ]
    body = []
    for r in rows:
        scope, ind_id, key, w, d, direction, l1, l2, l3 = r
        body.append(
            f'        "{scope}", {ind_id}, "{key}", "{w}", "{d}", "{direction}", '
            f"{_num_or_null(l1)}, {_num_or_null(l2)}, {_num_or_null(l3)}"
        )
    lines.append(",\n".join(body))   # no trailing comma after the final row
    lines.append("    ]")
    lines.append("")
    lines.append("// Verify: 288 rows total, 96 per scope, non-null L1/L2/L3 counts per indicator.")
    lines.append("// EWI_AlertThreshold | summarize Rows = count() by Scope")
    lines.append("// EWI_AlertThreshold | summarize Rows = count(), WithL1 = countif(isnotnull(L1)) by IndicatorId, IndicatorKey")
    OUT_KQL.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    missing = [f for f in SCOPE_FILES.values() if not (INPUT_DIR / f).exists()]
    if missing:
        print("Missing input files:\n  " + "\n  ".join(missing), file=sys.stderr)
        return 1

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT_KQL.parent.mkdir(parents=True, exist_ok=True)

    rows: list[list[str]] = []
    for scope, fname in SCOPE_FILES.items():
        parsed = parse_scope(INPUT_DIR / fname)
        for ind_id in sorted(INDICATORS):
            key, direction = INDICATORS[ind_id]
            for w in WINDOWS:
                for d in DAYTYPES:
                    cell = parsed.get((ind_id, w, d), {})
                    rows.append([
                        scope, str(ind_id), key, w, d, direction,
                        cell.get("L1", ""), cell.get("L2", ""), cell.get("L3", ""),
                    ])

    with OUT.open("w", newline="", encoding="utf-8") as fh:
        wr = csv.writer(fh)
        wr.writerow(
            ["Scope", "IndicatorId", "IndicatorKey", "WindowCode", "DayType",
             "Direction", "L1", "L2", "L3"]
        )
        wr.writerows(rows)

    write_kql(rows)
    print(f"Wrote {len(rows)} rows -> {OUT.relative_to(REPO)}")
    print(f"Wrote loader        -> {OUT_KQL.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
